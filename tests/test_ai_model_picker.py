"""The AI Settings model field is marimo's dropdown, not a text input, and its model list is
marimo's registry (static/ai-models.js, generated by scripts/gen_ai_models.py)."""
import json
import re
import subprocess
from pathlib import Path

from vivarium_workbench.lib import ai_auth
from vivarium_workbench.lib.report import render_dashboard  # noqa: F401  (import proves the template deps load)

STATIC = Path(__file__).parent.parent / "vivarium_workbench" / "static"
TEMPLATE = Path(__file__).parent.parent / "vivarium_workbench" / "templates" / "index.html.j2"


def _registry():
    js = (STATIC / "ai-models.js").read_text()
    body = js.split("window.VivAiModels = ", 1)[1].rstrip().rstrip(";")
    return js, json.loads(body)


def test_registry_covers_the_supported_providers_with_real_models():
    js, reg = _registry()
    assert "GENERATED by scripts/gen_ai_models.py" in js and "marimo-team/marimo" in js
    assert set(reg) <= set(ai_auth.PROVIDERS) and {"openai", "anthropic", "google", "ollama", "opencode", "bedrock"} <= set(reg)
    for pid, g in reg.items():
        ids = [m["model"] for m in g["models"]]
        assert ids and len(ids) == len(set(ids)), f"{pid}: empty or duplicate models"
        assert all(m["name"] and isinstance(m["thinking"], bool) for m in g["models"])
        assert g["label"] and g["description"] and g["url"].startswith("https://")
    assert all(m["model"].startswith("gemini") for m in reg["google"]["models"]), "Vertex-only third-party ids are filtered"


def test_settings_model_field_is_a_dropdown_trigger_not_an_input():
    html = TEMPLATE.read_text()
    card = html[html.index('id="viv-ai-card"'):html.index("</aside>", html.index('id="viv-ai-card"'))]
    assert re.search(r'<button id="viv-ai-model"[^>]*aria-haspopup', card)
    assert 'id="viv-ai-model"' in card and '<input id="viv-ai-model"' not in card
    for gone in ("viv-ai-discover", "viv-ai-addmodel", "viv-ai-chips", "datalist"):
        assert gone not in card, f"{gone} is not part of marimo's model picker"


def test_the_picker_script_loads_before_the_panel_and_is_cache_busted():
    html = TEMPLATE.read_text()
    assert html.index("assets/ai-models.js") < html.index("assets/chat.js")
    assert "?v={{ asset_version }}" in html[html.index("assets/ai-models.js"):][:120]


def test_registry_file_is_valid_javascript():
    subprocess.run(["node", "--check", str(STATIC / "ai-models.js")], check=True)
