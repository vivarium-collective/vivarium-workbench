def test_old_full_download_widget_functions_removed():
    js = (_PKG / "static" / "study-detail.js").read_text(encoding="utf-8")
    assert "function _loadReadoutsDownload(" not in js
    assert "function _downloadAllRawData(" not in js
    assert "window._loadReadoutsDownload " not in js
    assert "window._loadReadoutsDownload=" not in js
    assert "window._downloadAllRawData" not in js


def test_readouts_tab_activation_calls_pointer_not_old_widget():
    js = (_PKG / "static" / "study-detail.js").read_text(encoding="utf-8")
    i = js.index("function _setStudyTab(")
    j = js.index("window._setStudyTab", i)
    body = js[i:j]
    assert "_loadReadoutsDownload()" not in body
    assert "_loadReadoutsDownloadPointer(" in body


def test_pointer_function_jumps_to_exports_via_gotostudytab():
    js = (_PKG / "static" / "study-detail.js").read_text(encoding="utf-8")
    assert "function _loadReadoutsDownloadPointer(" in js
    assert "window._loadReadoutsDownloadPointer = _loadReadoutsDownloadPointer;" in js
    i = js.index("function _loadReadoutsDownloadPointer(")
    j = js.index("window._loadReadoutsDownloadPointer", i)
    body = js[i:j]
    # Reuses C1's cross-tab helper — no bespoke tab-switch logic. (The call
    # is embedded in an onclick="..." HTML-attribute string, so its quotes
    # are backslash-escaped in the JS source: _gotoStudyTab(\'results\',...).)
    # Task E2 moved the raw-data-downloads group off Exports ('data') onto
    # Simulations ('simulate'); the study-spine reorg (spec §3.3) moved it
    # again, onto its own Results panel ('results'), and repointed this
    # pointer to match.
    assert "_gotoStudyTab(" in body
    # The 5-tab reorg consolidated Results under the Simulations tab ('simulate'),
    # so the pointer navigates there (anchoring on exports-downloads) — there is no
    # standalone 'results' tab any more.
    assert "gotoStudyTab(\\'simulate\\'" in body
    # Lands on the anchor the Results template now carries.
    assert "exports-downloads" in body
    # Same data source + filter predicate _loadResults (Results) uses, so the
    # pointer only appears when Results actually has something to show —
    # never pointing at an empty tab (brief: "prefer omitting the pointer
    # when there are no runs with data").
    assert "/api/simulations" in body
    assert "store_path" in body and "db_path" in body


def test_pointer_omits_itself_when_no_downloadable_data():
    js = (_PKG / "static" / "study-detail.js").read_text(encoding="utf-8")
