"""Task C4: consolidate the download surfaces into Exports.

The Exports tab (`data-kind="data"`) already aggregates per-run raw-emitter
downloads (`_loadRawData` / `#raw-data-list`, Fable §4.8) AND analysis result
files (`#data-files` / `#data-download-all`) — it is the single "get the
data" tab. The Readouts tab used to render a SECOND, full raw-download
widget (`#readouts-download`, populated by `_loadReadoutsDownload()` /
`_downloadAllRawData()`), duplicating the same per-run links Exports already
shows. C4 removes that duplicate widget and replaces it with a single
pointer that jumps to Exports via C1's `_gotoStudyTab('data', <anchor>)`.

See .superpowers/sdd/fable-increment-a/task-C4-brief.md.
"""
from __future__ import annotations

import pathlib
import tempfile
from pathlib import Path

from vivarium_workbench.lib.study_page import render_study_detail_html

_PKG = Path(__file__).parent.parent / "vivarium_workbench"


def _render(spec_extra=None):
    spec = {"name": "s1"}
    if spec_extra:
        spec.update(spec_extra)
    with tempfile.TemporaryDirectory() as d:
        return render_study_detail_html(pathlib.Path(d), "s1", spec)


# ---------------------------------------------------------------------------
# Template
# ---------------------------------------------------------------------------

def test_readouts_panel_no_longer_inlines_full_widget_markup():
    html = _render()
    # The mount point stays (JS decides pointer-vs-nothing at runtime) ...
    assert 'id="readouts-download"' in html
    # ... but the old widget's own markup (only ever JS-injected) must not be
    # statically present, and none of its literal strings leak into the
    # template either.
    assert "Download raw data</strong>" not in html


def test_exports_panel_unchanged_download_surfaces_present():
    """Exports must remain a superset: both download surfaces it already had
    (per-run raw data + analysis files) are still there, plus a new anchor
    id for the Readouts pointer to jump to."""
    html = _render()
    assert 'id="raw-data-list"' in html
    assert 'id="data-files"' in html
    assert 'id="data-download-all"' in html
    assert 'id="exports-downloads"' in html


def test_exports_bulk_download_button_present_hidden_by_default():
    """Review round 1 fix: the old Readouts widget's bulk "download all raw
    runs" convenience is a genuine capability, not just a set of per-run
    links — restore it AT the Exports raw-download group (not the unrelated
    analysis-file zip button). Static markup starts hidden; JS reveals it
    with a run count once /api/simulations resolves."""
    html = _render()
    assert 'id="raw-data-download-all"' in html
    assert 'onclick="_downloadAllRawExports()"' in html
    # Starts hidden — _loadRawData only reveals it once there's ≥1 run with
    # raw data (never shown for a study with zero downloadable runs).
    i = html.index('id="raw-data-download-all"')
    tag = html[max(0, i - 80):i + 120]
    assert "display:none" in tag
    # Scoped to the raw-run group, distinct from the analysis-file zip.
    assert 'id="data-download-all"' in html


